#!/usr/bin/env python3
"""Turn the symbol packs (symbols/<build>.toml) into the table compiled into Kaepora Core.

    python3 tools/kaepora_symbols.py out/symbols_gen.h

One pack per supported build of the game. Core picks the pack of the running game at start and
answers kae_sym / kae_field from it. Needs Python 3.11+ (tomllib).
"""
import re
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_.]*$")


def load_packs(folder=REPO / "symbols"):
    packs = []
    for path in sorted(Path(folder).glob("*.toml")):
        pack = tomllib.loads(path.read_text())
        pack["path"] = path
        check(pack)
        packs.append(pack)
    assert packs, f"no symbol packs in {folder}"
    return packs


def check(pack):
    where = pack["path"].name
    assert re.fullmatch(r"[0-9A-F]{40}", pack["build"]), f"{where}: build must be 40 hex digits, upper case"
    for key in ("nnmain", "mod0", "size"):
        assert key in pack["detect"], f"{where}: [detect] needs {key}"
    slots = [h["slot"] for h in pack.get("hookpoint", {}).values()]
    assert len(slots) == len(set(slots)), f"{where}: two hook points share a slot"
    for name in symbols(pack):
        assert NAME.match(name), f"{where}: bad symbol name {name!r}"
    for name in pack.get("field", {}):
        assert NAME.match(name), f"{where}: bad field name {name!r}"


def symbols(pack):
    """{name: offset} for everything kae_sym answers: functions, globals, 'vtable.<Name>'."""
    out = {}
    for kind, prefix in (("function", ""), ("global", ""), ("vtable", "vtable.")):
        for name, entry in pack.get(kind, {}).items():
            full = prefix + name
            assert full not in out, f"{pack['path'].name}: {full} is defined twice"
            out[full] = entry["offset"]
            alias = entry.get("alias")
            if alias:
                assert alias not in out, f"{pack['path'].name}: alias {alias} is defined twice"
                out[alias] = entry["offset"]
    return out


def table(rows, fmt):
    # sorted by the bytes of the name: Core finds entries with a binary search using the same order
    return "".join(fmt.format(name=name, value=value) for name, value in sorted(rows.items(), key=lambda r: r[0].encode()))


def generate(packs):
    out = ["// Generated by tools/kaepora_symbols.py from symbols/*.toml. Don't edit.\n"]
    for i, pack in enumerate(packs):
        syms = symbols(pack)
        fields = {name: entry["offset"] for name, entry in pack.get("field", {}).items()}
        hooks = pack.get("hookpoint", {})
        out.append(f"static const kp_sym_t syms_{i}[] = {{\n" + table(syms, '    {{ "{name}", {value:#x} }},\n') + "    { 0, 0 }\n};\n")
        out.append(f"static const kp_sym_t fields_{i}[] = {{\n" + table(fields, '    {{ "{name}", {value:#x} }},\n') + "    { 0, 0 }\n};\n")
        out.append(f"static const kp_hookpoint_t hookpoints_{i}[] = {{\n"
                   + "".join(f'    {{ "{name}", {h["site"]:#x}, {h["slot"]} }},\n' for name, h in sorted(hooks.items()))
                   + "    { 0, 0, 0 }\n};\n")
    out.append("const kp_build_t kp_builds[] = {\n")
    for i, pack in enumerate(packs):
        d = pack["detect"]
        syms, fields = symbols(pack), pack.get("field", {})
        out.append(f'    {{ "{pack["version"]}", "{pack["build"]}", {d["nnmain"]:#x}, {d["mod0"]:#x}, {d["size"]:#x},\n'
                   f'      {pack.get("core", {}).get("hook-slots", 0):#x}, syms_{i}, {len(syms)}, fields_{i}, {len(fields)},\n'
                   f'      hookpoints_{i}, {len(pack.get("hookpoint", {}))} }},\n')
    out.append("};\n")
    out.append(f"const unsigned kp_build_count = {len(packs)};\n")
    return "".join(out)


if __name__ == "__main__":
    text = generate(load_packs())
    Path(sys.argv[1]).write_text(text)
    print(f"{sys.argv[1]}: {text.count(chr(10))} lines")
