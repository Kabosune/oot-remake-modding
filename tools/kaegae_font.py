#!/usr/bin/env python3
"""Turn Core's bitmap font (api/core/font/spleen-8x16.bdf) into the table compiled into Core.

    python3 tools/kaegae_font.py out/font_gen.h

The font is Spleen 8x16 by Frederic Cambus (BSD 2-Clause, api/core/font/LICENSE). Core carries the
printable ASCII characters and Latin-1 (U+00A0 to U+00FF): 191 glyphs of 16 bytes, one byte per
row, the leftmost pixel in bit 7.
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BDF = REPO / "api" / "core" / "font" / "spleen-8x16.bdf"
WIDTH, HEIGHT = 8, 16
RANGES = ((0x20, 0x7E), (0xA0, 0xFF))


def read_bdf(path=BDF):
    """{code point: [16 row bytes]}"""
    glyphs, code, rows = {}, None, None
    for line in path.read_text().splitlines():
        if line.startswith("ENCODING "):
            code = int(line.split()[1])
        elif line == "BITMAP":
            rows = []
        elif line == "ENDCHAR":
            assert len(rows) == HEIGHT, f"U+{code:04X} has {len(rows)} rows"
            glyphs[code], rows = rows, None
        elif rows is not None:
            assert len(line) == 2, f"U+{code:04X}: wider than 8 pixels"
            rows.append(int(line, 16))
    return glyphs


def generate():
    glyphs = read_bdf()
    codes = [c for first, last in RANGES for c in range(first, last + 1)]
    missing = [f"U+{c:04X}" for c in codes if c not in glyphs]
    assert not missing, f"the font lacks {missing}"
    out = ["// Generated by tools/kaegae_font.py from api/core/font/spleen-8x16.bdf. Do not edit.",
           "// Spleen 8x16, Copyright (c) 2018-2026, Frederic Cambus. BSD 2-Clause: api/core/font/LICENSE.",
           f"#define KP_FONT_WIDTH {WIDTH}", f"#define KP_FONT_HEIGHT {HEIGHT}",
           f"#define KP_FONT_GLYPHS {len(codes)}",
           "static const uint8_t kp_font[KP_FONT_GLYPHS][KP_FONT_HEIGHT] = {"]
    for c in codes:
        out.append("    { " + ", ".join(f"0x{b:02X}" for b in glyphs[c]) + f" }},  // U+{c:04X}")
    out.append("};")
    out.append("// The glyph for a code point; '?' for one the font doesn't carry.")
    out.append("static inline const uint8_t *kp_font_glyph(uint32_t code) {")
    base = 0
    for first, last in RANGES:
        out.append(f"    if (code >= {first:#x} && code <= {last:#x}) return kp_font[code - {first:#x} + {base}];")
        base += last - first + 1
    out.append(f"    return kp_font['?' - {RANGES[0][0]:#x}];")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    Path(sys.argv[1]).write_text(generate())
