#!/usr/bin/env python3
"""Bake printable ASCII from a TrueType font into font.h (4-bit alpha). Needs Pillow.
    python3 genfont.py /usr/share/fonts/truetype/dejavu/DejaVuSans.ttf 26 > font.h"""
import sys
from PIL import Image, ImageDraw, ImageFont
path, px = sys.argv[1], int(sys.argv[2])
font = ImageFont.truetype(path, px)
ascent, descent = font.getmetrics()
glyphs, data = [], bytearray()
for code in range(32, 127):
    ch = chr(code)
    box = font.getbbox(ch) or (0, 0, 0, 0)
    w, h = max(box[2] - box[0], 0), max(box[3] - box[1], 0)
    img = Image.new("L", (max(w, 1), max(h, 1)), 0)
    ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255)
    px_ = [v >> 4 for v in img.tobytes()] if w and h else []
    if len(px_) & 1: px_.append(0)
    glyphs.append((len(data), w if h else 0, h if w else 0, box[0], box[1], round(font.getlength(ch))))
    data += bytes(px_[i] << 4 | px_[i + 1] for i in range(0, len(px_), 2))
print("/* Generated by genfont.py from DejaVu Sans (see FONT-LICENSE.txt). Do not edit. */")
print(f"#define KAE_FONT_PX {px}\n#define KAE_FONT_ASCENT {ascent}\n#define KAE_FONT_LINE {ascent + descent}")
print("static const struct { unsigned off; unsigned char w, h; signed char x, y; unsigned char adv; } kae_glyphs[95] = {")
for g in glyphs: print("    {%d, %d, %d, %d, %d, %d}," % g)
print("};\nstatic const unsigned char kae_font_data[%d] = {" % len(data))
for i in range(0, len(data), 24): print("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
print("};")
